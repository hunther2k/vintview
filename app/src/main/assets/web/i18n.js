let dict = de;
export let lang = 'de';

export function setLang(l) {
  lang = (l || '').toLowerCase().startsWith('de') ? 'de' : 'en';
  dict = lang === 'de' ? de : en;
  document.documentElement.lang = lang;
}

export function t(key, vars) {
  let s = dict[key] ?? de[key] ?? key;
  if (vars) for (const k in vars) s = s.replaceAll('{' + k + '}', vars[k]);
  return s;
}

export function applyI18n(root = document) {
  root.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll('[data-i18n-title]').forEach(el => {
    el.title = t(el.dataset.i18nTitle);
    el.setAttribute('aria-label', el.title);
  });
}

export function fmtSize(n) {
  if (!(n >= 0)) return '';
  const u = lang === 'de' ? ['B', 'KB', 'MB', 'GB'] : ['B', 'KB', 'MB', 'GB'];
  let i = 0;
  while (n >= 1024 && i < u.length - 1) { n /= 1024; i++; }
  return n.toLocaleString(lang, { maximumFractionDigits: i ? 1 : 0 }) + ' ' + u[i];
}

export function fmtDate(ts) {
  const d = new Date(ts);
  const now = new Date();
  const day = x => new Date(x.getFullYear(), x.getMonth(), x.getDate()).getTime();
  const diff = (day(now) - day(d)) / 86400000;
  const time = d.toLocaleTimeString(lang, { hour: '2-digit', minute: '2-digit' });
  if (diff === 0) return t('today') + ', ' + time;
  if (diff === 1) return t('yesterday') + ', ' + time;
  return d.toLocaleDateString(lang, { day: '2-digit', month: '2-digit', year: 'numeric' });
}
